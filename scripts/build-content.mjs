import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import MarkdownIt from 'markdown-it';
import texmath from 'markdown-it-texmath';
import katex from 'katex';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contentRoot = path.join(root, 'content');
const output = path.join(root, 'app/src/main/assets/content.js');
const md = new MarkdownIt({ html: true, linkify: false, typographer: false })
  .use(texmath, { engine: katex, delimiters: 'dollars', katexOptions: { throwOnError: true, strict: 'ignore', output: 'htmlAndMathml', trust: false } });

function validateMath(tokens, file) {
  let count = 0;
  for (const token of tokens) {
    if (token.children) count += validateMath(token.children, file);
    if (token.type.startsWith('math_')) {
      try {
        katex.renderToString(token.content, { throwOnError: true, strict: 'ignore', displayMode: token.type.includes('block'), trust: false });
      } catch (error) {
        throw new Error(`Invalid formula in ${file}: ${token.content}\n${error.message}`);
      }
      count++;
    }
    if (token.type === 'text' && /(^|[^\\])\$/.test(token.content)) {
      throw new Error(`Unrendered dollar delimiter in ${file}: ${token.content.slice(0, 100)}`);
    }
  }
  return count;
}

export function compileBook() {
  const book = JSON.parse(fs.readFileSync(path.join(contentRoot, 'book.json'), 'utf8'));
  const seen = new Set();
  let mathCount = 0;
  for (const chapter of book.chapters) {
    if (!chapter.id || seen.has(chapter.id)) throw new Error(`Duplicate/missing chapter id: ${chapter.id}`);
    seen.add(chapter.id);
    if (!chapter.lessons?.length) throw new Error(`Empty chapter: ${chapter.id}`);
    for (const lesson of chapter.lessons) {
      if (!lesson.id || seen.has(lesson.id)) throw new Error(`Duplicate/missing lesson id: ${lesson.id}`);
      seen.add(lesson.id);
      const filename = path.resolve(contentRoot, lesson.file);
      if (!filename.startsWith(contentRoot + path.sep)) throw new Error(`Invalid lesson path: ${lesson.file}`);
      const source = fs.readFileSync(filename, 'utf8');
      if (source.length < 900 || (source.match(/<details>/g) || []).length < 2) {
        throw new Error(`Lesson ${lesson.id} must have substantive text and at least two solved exercises`);
      }
      const tokens = md.parse(source, {});
      mathCount += validateMath(tokens, lesson.file);
      lesson.html = md.renderer.render(tokens, md.options, {});
      // Plain text is bundled separately for offline full-text search.
      lesson.plain = source
        .replace(/<\/?(?:details|summary)\b[^>]*>/g, ' ')
        .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&')
        .replace(/\\[A-Za-z]+/g, ' ')
        .replace(/[$*_#`{}\\]/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
      delete lesson.file;
    }
  }
  if (mathCount < book.chapters.length * 3) throw new Error('Too few rendered formulas');
  return { book, mathCount };
}

export function serializedBook(book) {
  // Escaping '<' also prevents accidental script termination should this ever be embedded.
  return `/* Generated by scripts/build-content.mjs; edit content/ instead. */\nwindow.BOOK_DATA = ${JSON.stringify(book).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { book, mathCount } = compileBook();
  fs.writeFileSync(output, serializedBook(book));
  console.log(`Compiled ${book.chapters.length} chapters, ${book.chapters.reduce((n, c) => n + c.lessons.length, 0)} lessons, ${mathCount} formulas.`);
}
